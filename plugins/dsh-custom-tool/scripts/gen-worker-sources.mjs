/**
 * Inline the bundled Monaco workers into src/client/monaco/workers.generated.ts
 * so the single client bundle carries its own worker sources (blob-URL classic
 * workers; no extra files need serving). The file is tracked in git; a
 * rebuild with an unchanged monaco version produces identical content.
 */
import { readFileSync, writeFileSync } from 'node:fs'

const editor = readFileSync(new URL('../lib/workers/editor-worker.entry.js', import.meta.url), 'utf8')
const ts = readFileSync(new URL('../lib/workers/ts-worker.entry.js', import.meta.url), 'utf8')

const contents = [
  '// GENERATED by scripts/gen-worker-sources.mjs from monaco-editor — do not edit.',
  '// Inline blob-worker sources keep the client bundle a single file.',
  `export const editorWorkerSource = ${JSON.stringify(editor)}`,
  `export const tsWorkerSource = ${JSON.stringify(ts)}`,
  '',
].join('\n')

writeFileSync(new URL('../src/client/monaco/workers.generated.ts', import.meta.url), contents)
console.log('dsh-custom-tool: worker sources inlined')
